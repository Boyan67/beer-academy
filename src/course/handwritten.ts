export function handwritten(slug: string): Question[] {
  return (ENTRIES[slug] ?? []).map((e, i) => {
    const id = `story:${slug}:${i}`;
    return "tf" in e
      ? trueFalse(id, e.prompt, e.tf, e.explain)
      : choiceFirstRight(id, e.prompt, e.pick, e.explain);
  });
}
