/**
 * Generates src/lib/beer-guide/map-data.ts — the outline maps behind the
 * style-origin pins. Run once whenever the regions change:
 *
 *   npm i --no-save world-atlas@2 topojson-client@3 topojson-simplify@3 d3-geo@3
 *   node scripts/build-map.mjs
 *
 * Data: Natural Earth 1:50m via world-atlas (public domain).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoMercator, geoPath } from "d3-geo";
import { feature, merge, mesh } from "topojson-client";
import { presimplify, simplify } from "topojson-simplify";

const require = createRequire(import.meta.url);
// Simplified to about a pixel at this size — the 50m data is far finer than a phone shows.
const topo = simplify(presimplify(JSON.parse(readFileSync(require.resolve("world-atlas/countries-50m.json"), "utf8"))), 0.002);
const countries = feature(topo, topo.objects.countries).features;

const WIDTH = 360;
const REGIONS = {
  europe: { lon: [-11, 24], lat: [42.5, 58.5], highlight: ["Germany", "Czechia", "Belgium", "Austria", "Poland", "United Kingdom", "Ireland"] },
  usa: { lon: [-125, -66.5], lat: [24.5, 49.5], highlight: ["United States of America"] },
};

const box = ([w, e], [s, n]) => ({
  type: "Feature",
  geometry: { type: "Polygon", coordinates: [[[w, s], [w, n], [e, n], [e, s], [w, s]]] },
});

const out = {};
for (const [key, r] of Object.entries(REGIONS)) {
  const probe = geoMercator().fitWidth(WIDTH, box(r.lon, r.lat));
  const [[, y0], [, y1]] = geoPath(probe).bounds(box(r.lon, r.lat));
  const height = Math.round(y1 - y0);
  const projection = geoMercator()
    .fitExtent([[0, 0], [WIDTH, height]], box(r.lon, r.lat))
    .clipExtent([[0, 0], [WIDTH, height]]);
  const path = geoPath(projection).digits(0);
  out[key] = {
    width: WIDTH,
    height,
    scale: +projection.scale().toFixed(4),
    translate: projection.translate().map((v) => +v.toFixed(4)),
    land: path(merge(topo, topo.objects.countries.geometries)),
    borders: path(mesh(topo, topo.objects.countries, (a, b) => a !== b)),
    countries: Object.fromEntries(r.highlight.map((name) => [name, path(countries.find((c) => c.properties.name === name))])),
  };
}

const file = new URL("../src/lib/beer-guide/map-data.ts", import.meta.url);
writeFileSync(
  file,
  `// Generated by scripts/build-map.mjs from Natural Earth (public domain). Do not edit.\n\nexport const MAP_DATA = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log(Object.entries(out).map(([k, v]) => `${k}: ${v.width}×${v.height}`).join(", "));
